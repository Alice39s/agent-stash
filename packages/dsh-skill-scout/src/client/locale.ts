/** 两种语言的字典。 */
export const SCOUT_DICTIONARIES: Readonly<Record<"en" | "zh", Readonly<Record<ScoutKey, string>>>> =
  {
    en: EN,
    zh: ZH,
  };

/** 组件收到的 `t`：键限定在本插件的字典里。 */
export type ScoutTranslate = Translate<ScoutKey>;

/** 注册两种语言的字典，返回注销函数。 */
export function registerLocale(locale: Locale): () => void {
  const disposers = Object.entries(SCOUT_DICTIONARIES).map(([language, dictionary]) =>
    locale.register(SCOUT_LOCALE, language, { ...dictionary }),
  );
  return () => {
    for (const dispose of disposers) dispose();
  };
}
